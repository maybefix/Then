/**
 * 同音異義語（同じ音読みを持つ漢語）の使い分けと、表記を決める手掛かり語。
 *
 * 異字同訓の表（{@link IJIDOKUN_GROUPS}）が政府の報告から機械的に起こせるのに
 * 対して、同音の漢語の使い分けを定めた告示・報告は無い。ここは『記者ハンドブック』
 * が示す使い分けの考え方に沿ってThenが編んだ一覧で、語義は一般的な国語辞典の
 * 説明の範囲に収めてある。判断が割れる語（配付・配布など）は入れていない。
 *
 * 手掛かり語は、その表記でしか使わない複合語・連語だけを載せる。どちらの表記でも
 * 使う語（「解放感」と「開放感」、「想像力」と「創造力」など）は決め手にならないので
 * 載せない。同じ項目の中で語が重複していないことは
 * `scripts/test-proofread-rules.mjs` で検査する。
 */

/** 手掛かり語と対象語の関係。 */
export type HomophoneRole =
  /** 直前に付く語。「品質保証」の「品質」。「損害の補償」「損害を補償」のように助詞で続く形も見る。 */
  | "前"
  /** 直後に付く語。「保証人」の「人」。 */
  | "後"
  /** 直後に来る述語。「関心を持つ」の「持つ」、「感心する」の「する」。 */
  | "述";

export type HomophoneCue = {
  role: HomophoneRole;
  word: string;
  /** その語が示す表記の番号。 */
  variant: number;
};

export type HomophoneGroup = {
  /** 検出項目のIDに使う。読みのローマ字。 */
  id: string;
  /** 項目の読み。 */
  reading: string;
  variants: { word: string; sense: string }[];
  cues: HomophoneCue[];
};

/** 手掛かり語を短く書くための組み立て。 */
const cues = (entries: [HomophoneRole, number, ...string[]][]): HomophoneCue[] =>
  entries.flatMap(([role, variant, ...words]) => words.map((word) => ({ role, word, variant })));

